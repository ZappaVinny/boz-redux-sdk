#!/usr/bin/env python3
"""Writes docs/internal/stdlib-coverage.md: how much of the game the standard library reaches.

Every reflected class, singleton, component table, event and console variable of the game
definition is reachable through the generic modules (boz.reflect, boz.entities, boz.game_events,
boz.console). "Covered" means a hand-written module (not the generated data files) names it:
a semantic API exists. Run after changing lib/boz: python3 tools/stdlib/coverage.py
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'bozkit'))
from bozkit.schema import gamedef_file  # noqa: E402
LIB = ROOT / 'lib' / 'boz'
OUT = ROOT / 'docs' / 'internal' / 'stdlib-coverage.md'
GENERATED = {'event_names.lua', 'reflection_data.lua', 'symbol_data.lua', 'world_data.lua', 'cvar_data.lua'}
AREAS = [('CDO', 'Dead Ops Arcade'), ('CAI', 'AI'), ('CIw', 'Marmalade engine'), ('CIs', 'Studio engine'),
         ('CFrontend', 'Front end'), ('CUI', 'UI'), ('CPickup', 'Pickups'), ('CWave', 'Rounds'),
         ('CWeapon', 'Weapons'), ('CPlayer', 'Player'), ('CLunar', 'Ascension'), ('CMonkey', 'Ascension'),
         ('CTeleport', 'Teleporters'), ('CPerk', 'Perks'), ('CMystery', 'Mystery box'), ('CPackAPunch', 'Pack-a-Punch')]


def area(name: str) -> str:
    for prefix, label in AREAS:
        if name.startswith(prefix):
            return label
    return 'Game'


def main() -> int:
    source = '\n'.join(p.read_text(encoding='utf-8') for p in sorted(LIB.glob('*.lua')) if p.name not in GENERATED)
    words = set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', source))
    reflection = tomllib.loads(gamedef_file('reflection').read_text(encoding='utf-8'))['class']
    events = tomllib.loads(gamedef_file('events').read_text(encoding='utf-8'))['event']
    runtime = tomllib.loads(gamedef_file('runtime').read_text(encoding='utf-8'))
    event_names = sorted({e['name'] for e in events} | set(runtime.get('events', {}).get('names', [])))
    console = tomllib.loads(gamedef_file('console').read_text(encoding='utf-8'))
    symbols = tomllib.loads(gamedef_file('symbols').read_text(encoding='utf-8'))
    singletons = sorted(g['name'][:-12] for g in symbols.get('global', []) if g['name'].endswith('::s_instance'))
    tables = sorted(g['name'][:-9] for g in symbols.get('global', []) if g['name'].endswith('::s_table'))
    classes = sorted({c['name'] for c in reflection} | set(singletons) | set(tables))
    covered_classes = [c for c in classes if c in words]
    covered_events = [e for e in event_names if e in words or e.removeprefix('SUBJECT_').lower() in words]
    cvars = sorted(c['name'] for c in console['cvar'])
    commands = sorted(c['name'] for c in console.get('command', []))
    covered_cvars = [c for c in cvars if c in words]
    covered_commands = [c for c in commands if c in words]
    fields = sum(len(c.get('fields', [])) for c in reflection)
    lines = ['# Standard library coverage', '',
             'Generated by `tools/stdlib/coverage.py`. Everything below is reachable from Lua through the',
             'generic modules: `boz.reflect` (every reflected field of every class and singleton),',
             '`boz.entities` (find, spawn, move, inspect, remove any entity; every component table),',
             '`boz.game_events` (every event), `boz.cvars` (every variable, typed, with its default and',
             'note; every command). "Covered" means',
             'a hand-written module names it, so a semantic API exists for it.', '',
             '| What | In the game definition | Covered by a module |', '| --- | --- | --- |',
             f'| Classes (reflected, singletons, component tables) | {len(classes)} | {len(covered_classes)} |',
             f'| Reflected fields | {fields} | all, by name (boz.reflect) |',
             f'| Events | {len(event_names)} | {len(covered_events)} |',
             f'| Console variables | {len(cvars)} | {len(covered_cvars)} (all typed in boz.cvars) |',
             f'| Console commands | {len(commands)} | {len(covered_commands)} (all in boz.cvars.commands) |',
             f'| Singletons | {len(singletons)} | all, by name (boz.reflect.singleton) |',
             f'| Component tables | {len(tables)} | all, by class (boz.entities, boz.components) |', '']
    by_area: dict[str, list[str]] = {}
    for name in classes:
        by_area.setdefault(area(name), []).append(name)
    lines += ['## Classes by area', '', '`[x]` a module covers it; `[ ]` generic access only.', '']
    for label in sorted(by_area):
        items = by_area[label]
        done = sum(1 for n in items if n in covered_classes)
        lines += [f'### {label} ({done}/{len(items)})', '']
        lines += [f'- [{"x" if n in covered_classes else " "}] {n}' for n in items]
        lines.append('')
    lines += ['## Events', '', f'{len(covered_events)} of {len(event_names)} named by a module; every one through '
              '`boz.game_events.on(name, fn)`.', '']
    lines += [f'- [{"x" if e in covered_events else " "}] {e}' for e in event_names]
    lines.append('')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{OUT}: classes {len(covered_classes)}/{len(classes)}, events {len(covered_events)}/{len(event_names)}, '
          f'cvars {len(covered_cvars)}/{len(cvars)}, commands {len(covered_commands)}/{len(commands)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
