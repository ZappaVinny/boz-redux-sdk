#!/usr/bin/env python3
"""Writes the standard library's data files from the game definition (the client cannot read
the gamedef's TOML from Lua):

    lib/boz/event_names.lua       every SUBJECT_* event name (boz.events: ids by IwHashString)
    lib/boz/reflection_data.lua   every reflected class: bases and fields (boz.reflect)
    lib/boz/symbol_data.lua       function and global offsets (boz.core, for older clients)
    lib/boz/cvar_data.lua         every console variable (type, default, note) and command (boz.cvars)

Run after the game definition changes: python3 tools/stdlib_data.py
"""
from __future__ import annotations

import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GAMEDEF = ROOT / 'gamedef'
LIB = ROOT / 'lib' / 'boz'
HEADER = '-- Generated by tools/stdlib_data.py from the game definition ({}). Do not edit by hand.\n'


def lua_string(text: str) -> str:
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def events() -> str:
    data = tomllib.loads((GAMEDEF / 'events' / 'boz-1.0.11.toml').read_text(encoding='utf-8'))
    runtime = tomllib.loads((GAMEDEF / 'runtime' / 'boz-1.0.11.toml').read_text(encoding='utf-8'))
    known = {e['name'] for e in data['event']}
    extra = [{'name': n} for n in runtime.get('events', {}).get('names', []) if n not in known]
    lines = [HEADER.format('gamedef/events, gamedef/runtime'), 'return {']
    for event in sorted(data['event'] + extra, key=lambda e: e['name']):
        sent = ', '.join(event.get('sent_by', [])[:6])
        handled = ', '.join(event.get('handled_by', [])[:6])
        note = f'  -- sent by {sent or "?"}; handled by {handled or "?"}' if sent or handled else ''
        lines.append(f'    {lua_string(event["name"])},{note}')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def reflection() -> str:
    data = tomllib.loads((GAMEDEF / 'reflection' / 'boz-1.0.11.toml').read_text(encoding='utf-8'))
    lines = [HEADER.format('gamedef/reflection'),
             '-- [class] = {bases = {{name, offset}, ...}, fields = {[field] = {offset, size, type}}}',
             'return {']
    for cls in sorted(data['class'], key=lambda c: c['name']):
        bases = ', '.join(f'{{{lua_string(b["name"])}, {b.get("offset", 0)}}}' for b in cls.get('bases', []))
        fields = ', '.join(f'[{lua_string(f["name"])}] = {{{f["offset"]}, {f["size"]}, {lua_string(f["type"])}}}'
                           for f in cls.get('fields', []))
        lines.append(f'    [{lua_string(cls["name"])}] = {{bases = {{{bases}}}, fields = {{{fields}}}}},')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def symbols() -> str:
    data = tomllib.loads((GAMEDEF / 'symbols' / 'boz-1.0.11.toml').read_text(encoding='utf-8'))
    globals_ = sorted(data.get('global', []), key=lambda g: g['name'])
    lines = [HEADER.format('gamedef/symbols'),
             '-- Image offsets (add game.base()) for clients whose own game definition predates a name.',
             '-- Functions carry the Thumb bit.',
             'return {', '    functions = {']
    for f in sorted(data['function'], key=lambda f: f['name']):
        lines.append(f'        [{lua_string(f["name"])}] = 0x{f["offset"] | (1 if f.get("thumb") else 0):x},')
    lines += ['    },', '    globals = {']
    for g in globals_:
        lines.append(f'        [{lua_string(g["name"])}] = 0x{g["offset"]:x},')
    lines += ['    },', '    singletons = {']
    for g in globals_:
        if g['name'].endswith('::s_instance'):
            lines.append(f'        {g["name"][:-len("::s_instance")]} = 0x{g["offset"]:x},')
    lines += ['    },', '    tables = {']
    for g in globals_:
        if g['name'].endswith('::s_table'):
            lines.append(f'        {g["name"][:-len("::s_table")]} = 0x{g["offset"]:x},')
    lines += ['    },', '}']
    return '\n'.join(lines) + '\n'


def cvars() -> str:
    data = tomllib.loads((GAMEDEF / 'console' / 'boz-1.0.11.toml').read_text(encoding='utf-8'))
    notes_path = ROOT / 'tools' / 'symbols' / 'console_notes.toml'
    notes = tomllib.loads(notes_path.read_text(encoding='utf-8')) if notes_path.is_file() else {}
    lines = [HEADER.format('gamedef/console, tools/symbols/console_notes.toml'),
             '-- [name] = {type, default, note}; commands = {[name] = {args, note}}', 'return {', '    cvars = {']
    for cvar in sorted(data['cvar'], key=lambda c: c['name'].lower()):
        note = notes.get('cvar', {}).get(cvar['name'], {}).get('note', '')
        default = cvar.get('default')
        lines.append(f'        [{lua_string(cvar["name"])}] = {{{lua_string(cvar.get("type", ""))}, '
                     f'{lua_string(str(default)) if default is not None else "nil"}, {lua_string(note)}}},')
    lines += ['    },', '    commands = {']
    seen = set()
    for command in sorted(data.get('command', []), key=lambda c: c['name'].lower()):
        if command['name'] in seen:
            continue
        seen.add(command['name'])
        entry = notes.get('command', {}).get(command['name'], {})
        lines.append(f'        [{lua_string(command["name"])}] = {{{lua_string(entry.get("args", ""))}, '
                     f'{lua_string(entry.get("note", ""))}}},')
    lines += ['    },', '}']
    return '\n'.join(lines) + '\n'


def main() -> int:
    for name, text in (('event_names.lua', events()), ('reflection_data.lua', reflection()),
                       ('symbol_data.lua', symbols()), ('cvar_data.lua', cvars())):
        (LIB / name).write_text(text, encoding='utf-8', newline='\n')
        print(f'{LIB / name}: {len(text.splitlines())} lines')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
